-- ============================================================================
-- PostgreSQL 003_auth_and_images.sql
--  * product_images   : product pictures stored in the database (replaces the image server).
--  * auth_tokens / token_access_logs : the tables config/trackToken.js already writes to.
--    Until now they did not exist, so every tracking insert failed. token_access_logs grows with
--    traffic: the API prunes rows older than TOKEN_LOG_RETENTION_DAYS (default 90) on boot and daily.
-- Idempotent.
-- ============================================================================

CREATE TABLE IF NOT EXISTS product_images (
  product_id     BIGINT       PRIMARY KEY,
  content_type   TEXT         NOT NULL CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
  byte_size      INTEGER      NOT NULL CHECK (byte_size > 0 AND byte_size <= 5242880),
  sha256         CHAR(64)     NOT NULL,
  original_name  TEXT,
  data           BYTEA        NOT NULL,
  created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT product_images_size_matches CHECK (octet_length(data) = byte_size)
);

CREATE TABLE IF NOT EXISTS auth_tokens (
  token_hash   TEXT         PRIMARY KEY,
  user_id      TEXT         NOT NULL,
  issuer       TEXT,
  audience     TEXT,
  issued_at    TIMESTAMPTZ,
  expires_at   TIMESTAMPTZ,
  ttl_seconds  INTEGER,
  source       TEXT,
  permissions  JSONB        NOT NULL DEFAULT '[]'::jsonb,
  first_seen   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  last_seen    TIMESTAMPTZ  NOT NULL DEFAULT now(),
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_auth_tokens_user ON auth_tokens (user_id);
CREATE INDEX IF NOT EXISTS ix_auth_tokens_expires ON auth_tokens (expires_at);

CREATE TABLE IF NOT EXISTS token_access_logs (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash    TEXT,
  user_id       TEXT,
  request_path  TEXT,
  ip_address    TEXT,
  accessed_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_token_access_logs_time ON token_access_logs (accessed_at);
CREATE INDEX IF NOT EXISTS ix_token_access_logs_token ON token_access_logs (token_hash);
